def main() -> int:
    out_dir = Path("data/factbook_sft")
    out_dir.mkdir(parents=True, exist_ok=True)

    rows = []
    for q1, q2, answer in FACTS:
        for q in (q1, q2):
            rows.append({"instruction": q, "answer": answer, "source": "fact_table"})

    train_path = out_dir / "train.jsonl"
    with open(train_path, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    n_chars = sum(len(r["instruction"]) + len(r["answer"]) for r in rows)
    print(f"เขียน {len(rows)} คู่ ({len(FACTS)} ข้อเท็จจริง x 2 คำถาม) -> {train_path}")
    print(f"ตัวอักษรรวม: {n_chars:,} (~{n_chars // 3:,} token โดยประมาณ)")
    return 0


